"""Supervise one persistent tokenizer preparation panel, without inference."""
import json
from pathlib import Path
import time

import campaign
import fixed_workload
import input_panel_worker
import node_smoke
import runtime
import supervisor
import streamed_input_source


def check_progress(progress, spec, began_ns, now_ns):
    """Enforce actual initialization/task bounds outside the worker process."""
    if not isinstance(progress, dict):
        raise ValueError('worker progress is not an object')
    phase = progress.get('phase')
    if phase == 'tokenizer_initializing':
        started = progress.get('started_ns')
        bound = spec['initialization_timeout_seconds']
    elif phase == 'task_started':
        matches = [j for j in spec['jobs'] if j['run_id'] == progress.get('run_id')]
        if len(matches) != 1:
            raise ValueError('unknown worker population')
        job = matches[0]
        if (progress.get('cell_id') != job['cell_id'] or
                progress.get('repetition') != job['repetition'] or
                type(progress.get('index')) is not int or not 0 <= progress['index'] < job['concurrency'] or
                progress.get('task_timeout_seconds') != job['task_timeout_seconds']):
            raise ValueError('worker task progress differs from frozen specification')
        started, bound = progress.get('started_ns'), job['task_timeout_seconds']
    elif phase == 'task_committed':
        matches = [j for j in spec['jobs'] if j['run_id'] == progress.get('run_id')]
        if (len(matches) != 1 or type(progress.get('index')) is not int or
                not 0 <= progress['index'] < matches[0]['concurrency']):
            raise ValueError('unknown committed worker task')
        # A committed checkpoint does not grant an unbounded inter-task pause.
        started, bound = progress.get('finished_ns'), 10
    else:
        raise ValueError('unknown worker progress phase')
    if type(started) is not int or not began_ns <= started <= now_ns:
        raise ValueError('worker progress clock differs')
    if now_ns - started > bound * 10**9:
        raise TimeoutError('owned input worker exceeded its frozen progress bound')
    if now_ns + spec['cleanup_seconds'] * 10**9 >= spec['deadline_ns']:
        raise TimeoutError('input panel reached its fixed cleanup boundary')


def monitor_worker(session, child, output, spec, began_ns):
    while child.poll() is None:
        session.ensure_healthy()
        now = time.monotonic_ns()
        path = output/'worker-progress.json'
        if path.exists():
            check_progress(node_smoke.read(path), spec, began_ns, now)
        elif now - began_ns > 10 * 10**9:
            raise TimeoutError('owned worker did not publish initial progress')
        if now + spec['cleanup_seconds'] * 10**9 >= spec['deadline_ns']:
            raise TimeoutError('input panel reached its fixed cleanup boundary')
        time.sleep(.25)
    session.ensure_healthy()
    if child.returncode != 0:
        raise runtime.RuntimeErrorClosed('owned input worker failed; checkpoints and log retained')
    result = node_smoke.read(output/'worker-result.json')
    expected = [(j['run_id'], j['cell_id'], j['repetition'], j['concurrency']) for j in spec['jobs']]
    actual = [(j['run_id'], j['cell_id'], j['repetition'], j['tasks']) for j in result['populations']]
    if (result.get('status') != 'all_declared_tasks_generated_and_tokenizer_verified' or actual != expected or
            result.get('tokenizer_initializations') != 1 or result.get('scientific_acceptance') is not False or
            result.get('new_tasks') != sum(j['concurrency'] for j in spec['jobs']) or result.get('reused_tasks') != 0):
        raise ValueError('worker result does not cover the frozen input panel')
    for row in result['populations']:
        if input_panel_worker.sha(output/row['run_id']/'fixed-tasks.json') != row['tasks_sha256']:
            raise ValueError('final population bytes differ from worker result')
    return result


def validate_panel(config, deadline_ns):
    spec = dict(config['input_panel'])
    if 'deadline_ns' in spec:
        raise ValueError('panel clock must come from the fixed node session deadline')
    spec['deadline_ns'] = deadline_ns
    jobs = input_panel_worker.validate(spec)
    if any(j['retained_tasks'] for j in jobs):
        raise ValueError('completed populations are linked separately, never regenerated by this driver')
    if (config.get('task_family') != 'fixed' or config.get('layout') != '2xtp4' or
            config.get('fixed_prompt_version') != fixed_workload.PERFORMANCE_VERSION or
            config.get('cell_id') != jobs[0]['cell_id']):
        raise ValueError('input panel source configuration differs')
    matrix = node_smoke.read(config['matrix'])
    if matrix != node_smoke.read(campaign.HERE/'comparison-matrix.json'):
        raise ValueError('input panel matrix differs from installed source')
    cells = {c['id']: c for c in campaign.ledger(config['matrix'])['cells']}
    for job in jobs:
        cell = cells.get(job['cell_id'])
        if (cell is None or cell['layout'] != config['layout'] or cell['input_tokens'] != spec['input_tokens'] or
                cell['output_tokens'] != spec['output_tokens'] or cell['cache'] != spec['cache'] or
                cell['concurrency'] != job['concurrency'] or not 0 <= job['repetition'] < cell['repetitions']):
            raise ValueError('input job differs from the scientific matrix')
    if spec['cache'] == 'warm_prefix':
        evidence = Path(config['cache_config_evidence'])
        runtime.verify_evidence_manifest(evidence.parent)
        prior = node_smoke.read(evidence.parent/'run-config.json')
        old_manifest = node_smoke.read(evidence.parent/'manifest.json')
        new_manifest = node_smoke.read(config['manifest'])
        if (evidence.name != 'cache-config.json' or prior['layout'] != config['layout'] or
                prior['image'] != config['image'] or
                node_smoke.read(evidence.parent/'smoke-result.json')['status'] != 'passed' or
                node_smoke.read(evidence)['block_size'] != spec['block_size'] or
                old_manifest['plan_sha256'] != new_manifest['plan_sha256'] or
                old_manifest['matrix_sha256'] != new_manifest['matrix_sha256'] or
                old_manifest['runtime']['starting_profiles'][config['layout']] !=
                new_manifest['runtime']['starting_profiles'][config['layout']]):
            raise ValueError('live warm cache construction binding differs')
    return spec


def run(config):
    image_q, _, seconds = node_smoke.validate(config)
    deadline_ns = time.monotonic_ns() + int(seconds * 1e9)
    spec = validate_panel(config, deadline_ns)
    root = Path(config['run_dir'])
    model = Path(config['model_dir']).resolve(strict=True)
    source = Path(__file__).resolve().parent
    if any(',' in str(p) for p in (root, model, source)):
        raise ValueError('container mount path contains comma')
    with supervisor.Supervisor(node_smoke.NODE_LOCK, root, config['run_id'], deadline_ns,
                               phase='prompt-generation') as session:
        runtime.atomic_json(root/'run-config.json', config)
        runtime.atomic_json(root/'input-spec.json', spec)
        for key, name in [('manifest', 'manifest.json'), ('checkpoint_receipt', 'checkpoint-receipt.json'),
                          ('image_qualification', 'image-qualification.json')]:
            runtime.atomic_bytes(root/name, Path(config[key]).read_bytes())
        output = root/'output'
        output.mkdir()
        limit = time.monotonic() + 15
        while not (root/'watchdog-heartbeat.json').exists():
            session.ensure_healthy()
            if time.monotonic() >= limit:
                raise TimeoutError('watchdog startup timeout')
            time.sleep(.1)
        session.preflight([])
        runtime.atomic_json(root/'retirement-preflight.json', runtime.verify_retirement(config))
        argv = ['docker', 'run', '-d', '--network', 'none', '--gpus', 'all', '--restart', 'no',
                '--label', 'campaign=dsv41-1017', '--label', 'run_id='+config['run_id'],
                '--mount', f'type=bind,src={source},dst=/campaign,readonly',
                '--mount', f'type=bind,src={model},dst=/model,readonly',
                '--mount', f'type=bind,src={root / "input-spec.json"},dst=/input-spec.json,readonly',
                '--mount', f'type=bind,src={output},dst=/output',
                '--user', f'{output.stat().st_uid}:{output.stat().st_gid}',
                '--entrypoint', 'sleep', config['image'], 'infinity']
        cid = session.create_start(argv)
        row = runtime.inspect_owned(cid, config['run_id'])
        if row.get('Image') != image_q['image_id'] or row.get('State', {}).get('Running') is not True:
            raise runtime.RuntimeErrorClosed('input container image differs')
        began = time.monotonic_ns()
        child = session.start_input_worker(cid)
        result = monitor_worker(session, child, output, spec, began)
    populations = streamed_input_source.project(root, spec, config)
    runtime.atomic_json(root/'input-panel-result.json', {
        'status': 'passed', 'cleanup': 'passed', 'populations': result['populations'],
        'projected_sources': populations,
        'tasks': result['new_tasks'], 'scientific_acceptance': False,
        'scope': 'installed tokenizer generation only; independent lineage acceptance remains required'})
    runtime.seal_evidence(root)
